import assert from 'node:assert/strict';
import fs from 'node:fs';
const app=fs.readFileSync('portal-app.js','utf8');
const editor=fs.readFileSync('portal-diagnosis-report-editor.js','utf8');
assert.match(app,/portal-diagnosis-report-editor\.js\?v=\$\{BUILD\}/,'admin boot must load the report editor');
assert.ok(app.indexOf('portal-diagnosis-review-ux.js')<app.indexOf('portal-diagnosis-report-editor.js'),'editor must load after diagnosis review UX');
assert.match(editor,/if\(!state\.admin\)throw new Error/,'editor must fail closed outside admin workspace');
assert.match(editor,/nexus_effective_client_report/,'preview must use the server-authoritative effective report');
assert.match(editor,/nexus_add_diagnosis_report_adjustment/,'edits must use audited adjustment RPC');
assert.match(editor,/nexus_revoke_diagnosis_report_adjustment/,'restore must revoke adjustments instead of mutating source AI output');
assert.match(editor,/replace_executive_summary/);
assert.match(editor,/replace_first_move/);
assert.match(editor,/rewrite_opportunity/);
assert.match(editor,/hide_opportunity/);
assert.match(editor,/add_opportunity/);
assert.match(editor,/original AI diagnosis remains immutable/i,'founder must be told the provenance boundary');
assert.match(editor,/Client-safe preview/,'founder must preview the released projection');
assert.equal(/\.from\('nexus_diagnosis_runs'\).*update/s.test(editor),false,'browser editor must never mutate the original diagnosis row');
assert.equal(/service[_-]?role|SUPABASE_SERVICE|SECRET_KEY|RESEND_API_KEY|TWILIO_AUTH_TOKEN/.test(editor),false,'browser editor must not contain privileged credentials');
